import { chromium } from "playwright";
const [BASE, DOC, ADMIN, PW] = [process.env.BASE, process.env.DOC, process.env.A, process.env.P];
const b = await chromium.launch(); const c = await b.newContext({ baseURL: BASE }); const p = await c.newPage();
const problems = []; p.on("console", (m) => { if (m.type() === "error") problems.push(m.text()); }); p.on("pageerror", (e) => problems.push(String(e)));
const reqs = []; p.on("request", (r) => reqs.push(r.url()));
await p.goto("/login"); await p.fill("input[name=email]", ADMIN); await p.fill("input[name=password]", PW); await p.click("button[type=submit]"); await p.waitForURL(`${BASE}/accueil`);
await p.goto(`/d/${DOC}`); await p.getByText("Data: la dérivée").waitFor();
const img = p.locator("img[alt='notion image']");
await img.waitFor();
const ok = await img.evaluate((i) => new Promise((r) => { if (i.complete) r(i.naturalWidth > 0); i.onload = () => r(true); i.onerror = () => r(false); }));
console.log(ok ? "ok  " : "FAIL", "image servie depuis la plateforme", await img.getAttribute("src"));
const evil = await p.getByRole("link", { name: "piège" }).getAttribute("href");
console.log(evil === "#" ? "ok  " : "FAIL", "lien javascript: neutralisé", evil);
console.log(reqs.some((u) => u.includes("notion.")) ? "FAIL" : "ok  ", "aucune requête vers Notion");
await p.setViewportSize({ width: 1280, height: 800 }); await p.screenshot({ path: "/shots/notion.png" });
await p.getByRole("link", { name: "Chapitre 1" }).click(); await p.getByText("Dans la sous-page").waitFor();
console.log("ok   sous-page accessible");
const anon = await b.newContext({ baseURL: BASE });
const status = (await anon.request.get(process.env.ASSET)).status();
console.log(status === 404 ? "ok  " : "FAIL", "image Notion inaccessible sans session", status);
console.log(problems.length ? "FAIL console : " + problems.join(" | ") : "ok   aucune erreur console ni CSP");
await b.close();
